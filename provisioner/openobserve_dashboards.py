"""OpenObserve dashboards (dashboard format version 8), built at runtime by provisioner/provision.py:
one "API Service" dashboard per traces stream that exists in OpenObserve. Nothing is written to the repo.

    python3 provisioner/openobserve_dashboards.py sclaser_food sclaser-food    # print one dashboard (stream, default service)

Only logs and traces live here; machines and service status are in Grafana (provisioner/grafana/).
  traces   one stream per project (OTLP, routed by the collector); Next.js request spans have next_span_type='BaseServer.handleRequest'
           and http_route / http_status_code; the root http span carries enduser_id
  logs     same project stream (OTLP from pino); severity, body, trace_id, span_id, request_* on errors
"""
import json
import sys

# Layouts below are written on a 48-column grid with ~34px rows; schema v8 uses 192 columns and 17px rows.
GRID_W = 48
X_SCALE, Y_SCALE = 4, 2

# ----------------------------------------------------------------------------------------- panel helpers
_EMPTY_FILTER = {"filterType": "group", "logicalOperator": "AND", "conditions": []}


def _config(unit=None, decimals=None, **extra):
    cfg = {"show_legends": True, "legends_position": None, "decimals": decimals if decimals is not None else 1,
           "axis_border_show": False, "connect_nulls": False, "no_value_replacement": "",
           "wrap_table_cells": False, "table_transpose": False, "table_dynamic_columns": False,
           "drilldown": [], "mark_line": []}
    if unit:
        cfg["unit"] = unit
    if unit and unit not in ("default", "bytes", "percent", "seconds", "milliseconds", "short"):
        cfg["unit"], cfg["unit_custom"] = "custom", unit
    cfg.update(extra)
    return cfg


def _axis(alias, label, column=None, agg=None):
    item = {"label": label, "alias": alias, "column": column or alias, "color": None, "isDerived": False}
    if agg:
        item["aggregationFunction"] = agg
    return item


def sql(title, typ, query, stream, x=(), y=(), breakdown=(), stream_type="traces", unit=None,
        decimals=None, description="", **cfg):
    """x / y / breakdown: lists of (alias, label) matching the SELECT aliases."""
    if typ == "table" and decimals is None:
        decimals = 0  # counts and status codes; durations are already ROUNDed in the SQL
    return {
        "type": typ, "title": title, "description": description,
        "config": _config(unit, decimals, **cfg), "queryType": "sql",
        "queries": [{
            "query": query, "vrlFunctionQuery": "", "customQuery": True,
            "fields": {"stream": stream, "stream_type": stream_type,
                       "x": [_axis(a, l) for a, l in x], "y": [_axis(a, l) for a, l in y], "z": [],
                       "breakdown": [_axis(a, l) for a, l in breakdown], "filter": _EMPTY_FILTER},
            "config": {"promql_legend": "", "limit": 0},
        }],
    }


def dashboard(title, description, rows, variables=None, period="1h"):
    """rows: list of (height, [(width, panel), ...]); panels are laid out left to right, top to bottom."""
    panels, y = [], 0
    for height, row in rows:
        x = 0
        for width, p in row:
            n = len(panels) + 1
            layout = {"x": x * X_SCALE, "y": y * Y_SCALE, "w": width * X_SCALE, "h": height * Y_SCALE, "i": n}
            panels.append(dict(p, id=f"Panel_{n:03d}", layout=layout,
                               htmlContent="", markdownContent=""))
            x += width
        assert x <= GRID_W, f"{title}: row wider than the grid"
        y += height
    return {
        "version": 8, "title": title, "description": description,
        "tabs": [{"tabId": "default", "name": "Default", "panels": panels}],
        "variables": {"list": variables or [], "showDynamicFilters": False},
        "defaultDatetimeDuration": {"type": "relative", "relativeTimePeriod": period, "startTime": 0, "endTime": 0},
    }


# ----------------------------------------------------------------------------------------- API service
# One dashboard per project stream (the collector routes each project's traces and logs to its own stream).
def api_service(stream, default_service=""):
    def q(*args, **kwargs):
        return sql(*args, stream=stream, **kwargs)

    SVC = "service_name = '$service'"
    REQ = f"{SVC} AND next_span_type = 'BaseServer.handleRequest' AND http_route IS NOT NULL"  # one per request
    STATUS = "CAST(http_status_code AS INT)"
    MS = "duration / 1000.0"  # span duration is stored in microseconds

    return dashboard(
        f"API Service 服務 · {stream}",
        "Requests, latency, users and logs of one API service (traces + logs over OpenTelemetry). "
        "Open a trace_id in Traces for the full request. Generated by the observability stack: edits made here are reverted.",
        [
            (6, [(12, q("請求數 Requests", "metric", f"SELECT COUNT(*) AS y_axis_1 FROM \"{stream}\" WHERE {REQ}",
                          y=[("y_axis_1", "Requests")], decimals=0)),
                 (12, q("5xx 錯誤 Errors", "metric",
                          f"SELECT COUNT(*) AS y_axis_1 FROM \"{stream}\" WHERE {REQ} AND {STATUS} >= 500",
                          y=[("y_axis_1", "Errors")], decimals=0)),
                 (12, q("p95 延遲 Latency", "metric",
                          f"SELECT approx_percentile_cont({MS}, 0.95) AS y_axis_1 FROM \"{stream}\" WHERE {REQ}",
                          y=[("y_axis_1", "p95")], unit="milliseconds", decimals=0)),
                 (12, q("使用者 Active users", "metric",
                          f"SELECT COUNT(DISTINCT enduser_id) AS y_axis_1 FROM \"{stream}\" WHERE {SVC} AND enduser_id IS NOT NULL",
                          y=[("y_axis_1", "Users")], decimals=0))]),
            (9, [(24, q("請求 Requests by status", "stacked",
                          f"SELECT histogram(_timestamp) AS x_axis_1, COUNT(*) AS y_axis_1, "
                          f"CASE WHEN {STATUS} >= 500 THEN '5xx' WHEN {STATUS} >= 400 THEN '4xx' ELSE '2xx/3xx' END AS breakdown_1 "
                          f"FROM \"{stream}\" WHERE {REQ} GROUP BY x_axis_1, breakdown_1 ORDER BY x_axis_1",
                          x=[("x_axis_1", "Time")], y=[("y_axis_1", "Requests")], breakdown=[("breakdown_1", "Status")],
                          decimals=0)),
                 (24, q("延遲 Latency (ms)", "line",
                          f"SELECT histogram(_timestamp) AS x_axis_1, approx_percentile_cont({MS}, 0.5) AS y_axis_1, "
                          f"approx_percentile_cont({MS}, 0.95) AS y_axis_2 FROM \"{stream}\" WHERE {REQ} "
                          f"GROUP BY x_axis_1 ORDER BY x_axis_1",
                          x=[("x_axis_1", "Time")], y=[("y_axis_1", "p50"), ("y_axis_2", "p95")],
                          unit="milliseconds", decimals=0))]),
            (10, [(28, q("路由 Routes", "table",
                           f"SELECT http_route AS route, COUNT(*) AS requests, "
                           f"SUM(CASE WHEN {STATUS} >= 500 THEN 1 ELSE 0 END) AS errors_5xx, "
                           f"SUM(CASE WHEN {STATUS} >= 400 AND {STATUS} < 500 THEN 1 ELSE 0 END) AS errors_4xx, "
                           f"ROUND(AVG({MS}), 1) AS avg_ms, ROUND(approx_percentile_cont({MS}, 0.95), 1) AS p95_ms "
                           f"FROM \"{stream}\" WHERE {REQ} GROUP BY http_route ORDER BY requests DESC",
                           x=[("route", "Route"), ("requests", "Requests"), ("errors_5xx", "5xx"), ("errors_4xx", "4xx"),
                              ("avg_ms", "Avg ms"), ("p95_ms", "p95 ms")])),
                  (20, q("使用者 Requests by user", "table",
                           f"SELECT user_name AS username, enduser_id AS user_id, COUNT(*) AS requests, "
                           f"SUM(CASE WHEN span_status = 'ERROR' THEN 1 ELSE 0 END) AS errors, "
                           f"MAX(_timestamp) AS last_seen FROM \"{stream}\" WHERE {REQ} AND enduser_id IS NOT NULL "
                           f"GROUP BY user_name, enduser_id ORDER BY requests DESC",
                           x=[("username", "Username"), ("user_id", "User id"), ("requests", "Requests"),
                              ("errors", "Errors"), ("last_seen", "Last seen")]))]),
            (10, [(48, q("最慢的請求 Slowest requests", "table",
                           f"SELECT _timestamp AS time, http_method AS method, http_route AS route, {STATUS} AS status, "
                           f"ROUND({MS}, 1) AS duration_ms, trace_id FROM \"{stream}\" WHERE {REQ} "
                           f"ORDER BY duration DESC LIMIT 20",
                           x=[("time", "Time"), ("method", "Method"), ("route", "Route"), ("status", "Status"),
                              ("duration_ms", "ms"), ("trace_id", "trace_id")]))]),
            (9, [(48, q("日誌 Logs by severity", "stacked",
                          f"SELECT histogram(_timestamp) AS x_axis_1, COUNT(*) AS y_axis_1, severity AS breakdown_1 "
                          f"FROM \"{stream}\" WHERE {SVC} GROUP BY x_axis_1, breakdown_1 ORDER BY x_axis_1",
                          stream_type="logs", x=[("x_axis_1", "Time")], y=[("y_axis_1", "Logs")],
                          breakdown=[("breakdown_1", "Severity")], decimals=0))]),
            (12, [(48, q("錯誤日誌 Error logs (request body/headers are redacted)", "table",
                           f"SELECT _timestamp AS time, body AS message, request_method AS method, request_path AS path, "
                           f"exception_message AS error, trace_id FROM \"{stream}\" "
                           f"WHERE {SVC} AND severity IN ('error', 'fatal') ORDER BY _timestamp DESC LIMIT 50",
                           stream_type="logs",
                           x=[("time", "Time"), ("message", "Message"), ("method", "Method"), ("path", "Path"),
                              ("error", "Error"), ("trace_id", "trace_id")]))]),
        ],
        variables=[{
            "type": "query_values", "name": "service", "label": "Service",
            "query_data": {"stream_type": "traces", "stream": stream, "field": "service_name", "max_record_size": 100},
            "value": default_service, "options": [], "multiSelect": False,
        }],
    )


if __name__ == "__main__":
    print(json.dumps(api_service(*sys.argv[1:3]), ensure_ascii=False, indent=2))
